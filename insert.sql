-- 1) unit_price = ราคาสินค้าปัจจุบัน (ทุกบรรทัด รวมของ extra.sql เดิม)
UPDATE order_line
SET    unit_price = (SELECT p.price FROM product p WHERE p.product_id = order_line.product_id);

-- 2) sub_total = ผลรวมทุกบรรทัดของออเดอร์ (ใช้ subquery เพราะ UPDATE ... JOIN ปรับแต่ละแถวได้ครั้งเดียว)
UPDATE shop_order
SET    sub_total = COALESCE((SELECT SUM(ol.qty * ol.unit_price)
                             FROM   order_line ol
                             WHERE  ol.order_id = shop_order.order_id), 0);

-- 3) total = sub_total - discount
UPDATE shop_order
SET    total = sub_total - discount;
